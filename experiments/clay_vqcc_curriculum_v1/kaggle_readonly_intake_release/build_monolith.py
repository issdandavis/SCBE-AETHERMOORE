"""Render the Kaggle intake as one hash-verifying Python code file."""

from __future__ import annotations

import base64
from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path
import textwrap
import zipfile


HERE = Path(__file__).resolve().parent
SOURCE_ROOT = HERE.parent
MONOLITH_NAME = "clay_vqcc_readonly_intake.py"
RUNTIME_SOURCES = {
    "CAMPAIGN_SPEC.json": SOURCE_ROOT / "CAMPAIGN_SPEC.json",
    "EXECUTION_ADMISSION.json": HERE / "EXECUTION_ADMISSION.json",
    "build_vqcc_split.py": SOURCE_ROOT / "build_vqcc_split.py",
    "findings_task.py": SOURCE_ROOT / "findings_task.py",
    "kernel-metadata.json": HERE / "kernel-metadata.json",
    "load_vqcc_corpus.py": SOURCE_ROOT / "load_vqcc_corpus.py",
    "run_readonly_intake.py": SOURCE_ROOT / "run_readonly_intake.py",
    "runtime_main.py": HERE / "run_kaggle_readonly_intake.py",
    "vqcc_task.py": SOURCE_ROOT / "vqcc_task.py",
}


def _payload() -> tuple[bytes, dict[str, str]]:
    contents = {name: path.read_bytes() for name, path in sorted(RUNTIME_SOURCES.items())}
    buffer = BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, payload in contents.items():
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, payload)
    return buffer.getvalue(), {name: sha256(payload).hexdigest() for name, payload in contents.items()}


def render_monolith() -> bytes:
    payload, entry_hashes = _payload()
    encoded = base64.b85encode(payload).decode("ascii")
    chunks = "\n".join(f"    b{chunk!r}" for chunk in textwrap.wrap(encoded, width=100))
    entry_literal = json.dumps(entry_hashes, ensure_ascii=True, indent=2, sort_keys=True)
    source = f'''"""Self-contained Kaggle launcher for the sealed Clay VQCC intake.

Generated by build_monolith.py. Do not hand-edit.
"""

from __future__ import annotations

import base64
import hashlib
import importlib.util
import io
from pathlib import Path
import shutil
import sys
import tempfile
import zipfile


PAYLOAD_SHA256 = {sha256(payload).hexdigest()!r}
ENTRY_HASHES = {entry_literal}
PAYLOAD_B85 = (
{chunks}
)


def materialize_runtime() -> Path:
    payload = base64.b85decode(PAYLOAD_B85)
    if hashlib.sha256(payload).hexdigest() != PAYLOAD_SHA256:
        raise RuntimeError("embedded runtime payload hash differs")
    root = Path(tempfile.mkdtemp(prefix="clay-vqcc-intake-runtime-"))
    try:
        with zipfile.ZipFile(io.BytesIO(payload), "r") as archive:
            names = archive.namelist()
            if names != sorted(ENTRY_HASHES):
                raise RuntimeError("embedded runtime inventory differs")
            for name in names:
                if Path(name).name != name:
                    raise RuntimeError(f"unsafe embedded runtime path: {{name!r}}")
                data = archive.read(name)
                if hashlib.sha256(data).hexdigest() != ENTRY_HASHES[name]:
                    raise RuntimeError(f"embedded runtime file differs: {{name}}")
                (root / name).write_bytes(data)
        return root
    except BaseException:
        shutil.rmtree(root)
        raise


def main(argv=None) -> int:
    root = materialize_runtime()
    try:
        path = root / "runtime_main.py"
        spec = importlib.util.spec_from_file_location("clay_vqcc_intake_runtime", path)
        if spec is None or spec.loader is None:
            raise RuntimeError("could not load embedded runtime")
        module = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = module
        spec.loader.exec_module(module)
        return int(module.main(argv))
    finally:
        shutil.rmtree(root)


if __name__ == "__main__":
    raise SystemExit(main())
'''
    return source.encode("utf-8")
